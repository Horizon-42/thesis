#!/usr/bin/env python
"""Which executor limits bind, and how fast do bank, thrust and load factor actually change?

Three executors on the same flights (Δ = 2 s, words regenerated by each, official thresholds):
  OFFICIAL  original executor, point-mass plant, roll limit p = 5 deg/s (the command IS the actuator)
  NEW p=5   `lag_executor`, lag plant (tau thrust/bank/load = 1.5/2.0/0.8 s), p = 5 deg/s
  NEW p=30  the same with p = 30 deg/s (the roll limit no longer binds)

Per limit: the share of flown cycles where it bound (`Flown.limits`), and the share of flights where it ever bound.
Per actuator: the rate it actually changes at, from the commands the executor sent. On the lag plant the actuator is
rebuilt from the commands with the plant's own lag law, a(k+1) = u + (a(k) - u) exp(-dt / tau) (what the plant integrates
with a fixed-step RK4 at 0.5 s: exact to the 4th digit for these tau), starting from the plant's start state (thrust =
first command, bank 0, load factor 1). Two rates are reported: the MEAN over a 1 s cycle, (a(k+1) - a(k)) / dt, and the
PEAK at the start of the cycle, (u - a) / tau, which is where a first-order actuator is fastest.
On the point-mass plant the command is what flies, so its rate is the change of the command from cycle to cycle.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from collections import defaultdict
from dataclasses import replace
from pathlib import Path

import numpy as np
import torch

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import compare_compensation as cc   # noqa: E402
import compare_plants as cp         # noqa: E402
import lag_executor as le           # noqa: E402
from ts_transformer.autopilot import closed_loop, replay                                  # noqa: E402
from ts_transformer.autopilot import executor as executor_module                          # noqa: E402
from ts_transformer.autopilot import flights as flights_module                            # noqa: E402
from ts_transformer.autopilot.executor import LIMITS, MODES                               # noqa: E402
from ts_transformer.autopilot.plant import Plant                                          # noqa: E402
from ts_transformer.instructions.labeller.records import Refused                          # noqa: E402
from ts_transformer.repo_layout import arrival_manifest_path                              # noqa: E402

TAUS = np.array(cc.DEFAULT_TAUS)     # thrust, bank, load
ORIGINAL_EXECUTOR, ORIGINAL_PLANT = executor_module.Executor, Plant


def pct(a, qs=(50, 90, 99, 100)):
    a = np.asarray(a, dtype=float)
    a = a[np.isfinite(a)]
    return {f"p{q}": float(np.percentile(np.abs(a), q)) for q in qs} if a.size else {}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--per-airport", type=int, default=100)
    ap.add_argument("--seed", type=int, default=1337)
    ap.add_argument("--chunk", type=int, default=250)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    flights_module.arrival_manifest_path = lambda airport: arrival_manifest_path(airport, cp.HARVEST)
    cpu, started = torch.device("cpu"), time.perf_counter()
    params, record, words = replay.open_spec(cp.EXECUTOR, cp.INSTRUCTIONS)
    drawn = replay.draw(cp.INSTRUCTIONS, "train", words.spec, words, per_airport=args.per_airport, seed=args.seed,
                        groups=(replay.OWN, replay.STAND_IN), row_interval_s=2.0)
    print(f"{len(drawn.indices)} flights, {time.perf_counter() - started:.0f}s", flush=True)

    arms = [("OFFICIAL (original executor, point-mass, p = 5)", True, 5.0),
            ("NEW executor, lag plant, p = 5", False, 5.0),
            ("NEW executor, lag plant, p = 30", False, 30.0)]
    results = {}
    for name, pm, p in arms:
        if pm:
            le.uninstall(ORIGINAL_EXECUTOR, ORIGINAL_PLANT)
        else:
            le.install(cc.DEFAULT_TAUS, cc.DEFAULT_TAUS)
        run = replace(params, bank_rate_deg_s=p)
        regenerated = {}
        for i, r in zip(drawn.indices, closed_loop.read_chunked(drawn, run, words, chunk=args.chunk, device=cpu)):
            if not isinstance(r, Refused):
                regenerated[i] = r
        batch, _ = closed_loop.replay_batch(drawn, regenerated, words)
        names = LIMITS + MODES
        cycles_total = 0
        bind_cycles = {n: 0 for n in LIMITS}
        bind_flights = {n: 0 for n in LIMITS}
        rates = {"bank_mean": [], "bank_peak": [], "thrust_mean": [], "thrust_peak": [], "load_mean": [], "load_peak": []}
        magnitudes = {"bank_deg": [], "load": [], "thrust": []}
        flights_n = 0
        for first in range(0, len(batch.signals), args.chunk):
            part = replay.subset(batch, list(range(first, min(first + args.chunk, len(batch.signals)))))
            flown, verdicts = replay.fly_batch(part, run, words, device=cpu)
            cmd = flown.commands.numpy()             # [B, T, 3] thrust fraction, bank rad, load factor
            for j, verdict in enumerate(verdicts):
                end = int(verdict.end_row)
                if end < 3:
                    continue
                flights_n += 1
                u = cmd[j, :end]
                cycles_total += end
                for n in LIMITS:
                    hit = flown.limits[n][j, :end].numpy()
                    bind_cycles[n] += int(hit.sum())
                    bind_flights[n] += int(hit.any())
                if pm:
                    d = np.diff(u, axis=0)                            # per-cycle change of the flown command
                    rates["bank_mean"] += list(np.degrees(d[:, 1])); rates["bank_peak"] += list(np.degrees(d[:, 1]))
                    rates["thrust_mean"] += list(d[:, 0] * 100.0); rates["thrust_peak"] += list(d[:, 0] * 100.0)
                    rates["load_mean"] += list(d[:, 2]); rates["load_peak"] += list(d[:, 2])
                    a = u
                else:
                    a = np.empty_like(u)
                    a[0] = [u[0, 0], 0.0, 1.0]               # the plant's start state
                    k = np.exp(-1.0 / TAUS)
                    peak = np.empty_like(u)
                    for c in range(len(u) - 1):
                        peak[c] = (u[c] - a[c]) / TAUS
                        a[c + 1] = u[c] + (a[c] - u[c]) * k
                    peak[-1] = (u[-1] - a[-1]) / TAUS
                    mean = np.diff(a, axis=0)
                    rates["bank_mean"] += list(np.degrees(mean[:, 1])); rates["bank_peak"] += list(np.degrees(peak[:-1, 1]))
                    rates["thrust_mean"] += list(mean[:, 0] * 100.0); rates["thrust_peak"] += list(peak[:-1, 0] * 100.0)
                    rates["load_mean"] += list(mean[:, 2]); rates["load_peak"] += list(peak[:-1, 2])
                magnitudes["bank_deg"] += list(np.degrees(a[:, 1])); magnitudes["load"] += list(a[:, 2])
                magnitudes["thrust"] += list(a[:, 0])
        results[name] = {
            "flights": flights_n, "cycles": cycles_total,
            "bind_share_of_cycles": {n: bind_cycles[n] / cycles_total for n in LIMITS},
            "bind_share_of_flights": {n: bind_flights[n] / flights_n for n in LIMITS},
            "rates_abs": {k: pct(v) for k, v in rates.items()},
            "values": {"bank_deg_abs": pct(magnitudes["bank_deg"]), "load_factor": {
                "p1": float(np.percentile(magnitudes["load"], 1)), "p99": float(np.percentile(magnitudes["load"], 99)),
                "max": float(np.max(magnitudes["load"]))},
                "thrust_fraction": {"p1": float(np.percentile(magnitudes["thrust"], 1)),
                                    "p99": float(np.percentile(magnitudes["thrust"], 99)),
                                    "min": float(np.min(magnitudes["thrust"])), "max": float(np.max(magnitudes["thrust"]))}}}
        print(f"  {name}: {flights_n} flights, {cycles_total} cycles, {time.perf_counter() - started:.0f}s", flush=True)
    le.uninstall(ORIGINAL_EXECUTOR, ORIGINAL_PLANT)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(results, indent=1))
    print(f"→ {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
